    @Override
    @Transactional(readOnly = true)
    public CareerBuilderSummaryResponse getSummary(Long studentId, Long schoolId) {
        log.info("Fetching career-builder summary for student: {}, school: {}", studentId, schoolId);

        List<CareerAssessment> allAssessments =
                assessmentRepo.findBySchoolIdAndIsActiveTrueOrderByOrderIndexAsc(schoolId);

        Map<Long, CareerStudentProgress> progressMap = progressRepo
                .findByStudent_Id(studentId)
                .stream()
                .collect(Collectors.toMap(p -> p.getAssessment().getId(), p -> p, (a, b) -> a));

        Map<Long, CareerResult> resultMap = resultRepo
                .findByStudent_IdOrderByCreatedAtDesc(studentId)
                .stream()
                .collect(Collectors.toMap(r -> r.getAssessment().getId(), r -> r, (a, b) -> a));

        int total = allAssessments.size();
        long completed = progressMap.values().stream()
                .filter(p -> p.getStatus() == CareerAssessmentStatus.COMPLETED).count();
        long inProgressCount = progressMap.values().stream()
                .filter(p -> p.getStatus() == CareerAssessmentStatus.IN_PROGRESS).count();
        int pending = (int) (total - completed - inProgressCount);

        List<CareerAssessmentResponse> inProgressList = allAssessments.stream()
                .filter(a -> {
                    CareerStudentProgress p = progressMap.get(a.getId());
                    return p != null && p.getStatus() == CareerAssessmentStatus.IN_PROGRESS;
                })
                .map(a -> buildAssessmentResponse(a, progressMap.get(a.getId()), resultMap.get(a.getId())))
                .collect(Collectors.toList());

        List<CareerAssessmentResponse> pendingList = allAssessments.stream()
                .filter(a -> {
                    CareerStudentProgress p = progressMap.get(a.getId());
                    return p == null || p.getStatus() == CareerAssessmentStatus.PENDING;
                })
                .map(a -> buildAssessmentResponse(a, progressMap.get(a.getId()), resultMap.get(a.getId())))
                .collect(Collectors.toList());

        List<CareerAssessmentResponse> completedList = allAssessments.stream()
                .filter(a -> {
                    CareerStudentProgress p = progressMap.get(a.getId());
                    return p != null && p.getStatus() == CareerAssessmentStatus.COMPLETED;
                })
                .map(a -> buildAssessmentResponse(a, progressMap.get(a.getId()), resultMap.get(a.getId())))
                .collect(Collectors.toList());

        List<CareerAssessmentResponse> upcomingList = pendingList.stream()
                .limit(5)
                .collect(Collectors.toList());

        List<CareerReportResponse> reports = buildReportsList(allAssessments, resultMap);

        int avgScore = (int) Math.round(resultMap.values().stream()
                .map(CareerResult::getScore)
                .filter(Objects::nonNull)
                .mapToInt(Integer::intValue)
                .average()
                .orElse(0));

        List<CareerPerformanceTrendPointResponse> trend = resultMap.values().stream()
                .filter(r -> r.getScore() != null)
                .sorted(Comparator.comparing(r -> r.getProgress() != null && r.getProgress().getCompletedAt() != null
                        ? r.getProgress().getCompletedAt()
                        : r.getCreatedAt()))
                .limit(6)
                .map(r -> CareerPerformanceTrendPointResponse.builder()
                        .label((r.getProgress() != null && r.getProgress().getCompletedAt() != null
                                ? r.getProgress().getCompletedAt()
                                : r.getCreatedAt()).getMonth().name().substring(0, 3))
                        .score(r.getScore())
                        .build())
                .collect(Collectors.toList());

        return CareerBuilderSummaryResponse.builder()
                .totalAssignments(total)
                .pendingCount(Math.max(pending, 0))
                .completedCount((int) completed)
                .reportsAvailable((int) resultMap.values().stream()
                        .filter(CareerResult::getReportAvailable).count())
                .avgScore(avgScore)
                .upcomingAssessments(upcomingList)
                .pendingAssessments(pendingList)
                .inProgressAssessments(inProgressList)
                .completedAssessments(completedList)
                .recentReports(reports)
                .performanceTrend(trend)
                .build();
    }

