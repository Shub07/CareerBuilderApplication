    public CareerReportDownloadPayload downloadReport(Long resultId, Long studentId) {
        CareerResult result = resultRepo.findByIdAndStudent_Id(resultId, studentId)
                .orElseThrow(() -> new RuntimeException("Report not found for resultId: " + resultId));

        if (!Boolean.TRUE.equals(result.getReportAvailable())) {
            throw new RuntimeException("Report not available for resultId: " + resultId);
        }

        CareerAssessment assessment = result.getAssessment();
        List<String> strengths = fromJson(result.getStrengthAreasJson());
        List<String> interests = fromJson(result.getInterestIndicatorsJson());

        String content = "Career Builder Report\n"
                + "====================\n"
                + "Student ID: " + studentId + "\n"
                + "Assessment: " + assessment.getTitle() + "\n"
                + "Type: " + assessment.getType().getLabel() + "\n"
                + "Score: " + (result.getScore() != null ? result.getScore() : 0) + "%\n"
                + "Completed At: " + (result.getProgress() != null ? result.getProgress().getCompletedAt() : result.getCreatedAt()) + "\n\n"
                + "Strength Areas:\n- " + String.join("\n- ", strengths) + "\n\n"
                + "Interest Indicators:\n- " + String.join("\n- ", interests) + "\n";

        String safeTitle = assessment.getTitle().replaceAll("[^a-zA-Z0-9]+", "_").replaceAll("_+", "_");
        String fileName = safeTitle + "_Report_" + result.getId() + ".txt";

        return new CareerReportDownloadPayload(fileName, content.getBytes(StandardCharsets.UTF_8));
    }

