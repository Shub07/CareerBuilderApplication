    @Override
    public CareerResultResponse submit(Long assessmentId, Long studentId, CareerSubmitRequest request) {
        CareerStudentProgress progress = progressRepo
                .findByStudent_IdAndAssessment_Id(studentId, assessmentId)
                .orElseGet(() -> {
                    CareerAssessment a = assessmentRepo.findById(assessmentId)
                            .orElseThrow(() -> new RuntimeException("Assessment not found: " + assessmentId));
                    Student s = studentRepo.findById(studentId)
                            .orElseThrow(() -> new RuntimeException("Student not found: " + studentId));
                    return progressRepo.save(CareerStudentProgress.builder()
                            .student(s)
                            .assessment(a)
                            .status(CareerAssessmentStatus.IN_PROGRESS)
                            .currentQuestionIndex(0)
                            .build());
                });

        CareerAssessment assessment = progress.getAssessment();

        // Save all final answers
        if (request.answers() != null) {
            for (Map.Entry<Integer, Integer> entry : request.answers().entrySet()) {
                int questionOrder = entry.getKey();
                int selectedIndex = entry.getValue();

                assessment.getQuestions().stream()
                        .filter(q -> q.getQuestionOrder() == questionOrder)
                        .findFirst()
                        .ifPresent(question -> {
                            CareerStudentAnswer answer = answerRepo
                                    .findByProgress_IdAndQuestion_Id(progress.getId(), question.getId())
                                    .orElse(CareerStudentAnswer.builder()
                                            .progress(progress)
                                            .question(question)
                                            .answeredAt(LocalDateTime.now())
                                            .build());
                            answer.setSelectedOptionIndex(selectedIndex);
                            answer.setAnsweredAt(LocalDateTime.now());
                            answerRepo.save(answer);
                        });
            }
        }

        // Mark progress as completed
        progress.setStatus(CareerAssessmentStatus.COMPLETED);
        progress.setCompletedAt(LocalDateTime.now());
        progress.setCurrentQuestionIndex(assessment.getQuestions().size());
        progressRepo.save(progress);

        // Compute results
        List<CareerStudentAnswer> answers = answerRepo.findByProgress_Id(progress.getId());
        ComputedResult computed = computeResult(assessment, answers);

        // Save / update result
        CareerResult result = resultRepo
                .findByStudent_IdAndAssessment_Id(studentId, assessmentId)
                .orElse(CareerResult.builder()
                        .student(progress.getStudent())
                        .assessment(assessment)
                        .progress(progress)
                        .build());

        result.setStrengthAreasJson(toJson(computed.strengthAreas));
        result.setInterestIndicatorsJson(toJson(computed.interestIndicators));
        result.setScore(computed.score);
        result.setReportAvailable(true);
        resultRepo.save(result);

        log.info("Submitted career assessment {} for student {}, score={}", assessmentId, studentId, computed.score);

        return toResultResponse(result, assessment);
    }

