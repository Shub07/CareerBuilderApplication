    private CareerAssessmentResponse buildAssessmentResponse(CareerAssessment a,
                                                              CareerStudentProgress progress,
                                                              CareerResult result) {
        int total = a.getQuestions().size();
        String status = CareerAssessmentStatus.PENDING.name();
        int progressPercent = 0;
        Long progressId = null;
        LocalDateTime startedAt = null;
        LocalDateTime completedAt = null;

        if (progress != null) {
            status = progress.getStatus().name();
            progressId = progress.getId();
            startedAt = progress.getStartedAt();
            completedAt = progress.getCompletedAt();
            if (total > 0) {
                progressPercent = (int) Math.round(
                        (progress.getCurrentQuestionIndex() * 100.0) / total);
            }
            if (progress.getStatus() == CareerAssessmentStatus.COMPLETED) {
                progressPercent = 100;
            }
        }

        return CareerAssessmentResponse.builder()
                .id(a.getId())
                .title(a.getTitle())
                .description(a.getDescription())
                .type(a.getType().getLabel())
                .category(a.getCategory())
                .bgColor(a.getType().getBgColor())
                .estimatedMinutes(a.getEstimatedMinutes())
                .totalQuestions(total)
                .status(status)
                .progressPercent(progressPercent)
                .progressId(progressId)
                .startedAt(startedAt)
                .completedAt(completedAt)
                .hasResult(result != null)
                .build();
    }

