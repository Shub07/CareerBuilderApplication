    private ComputedResult computeResult(CareerAssessment assessment, List<CareerStudentAnswer> answers) {
        // Count trait tag frequency from selected options
        Map<String, Integer> traitCounts = new HashMap<>();

        for (CareerStudentAnswer answer : answers) {
            int selectedIdx = answer.getSelectedOptionIndex();
            CareerQuestion question = answer.getQuestion();

            question.getOptions().stream()
                    .filter(o -> o.getOptionIndex() == selectedIdx)
                    .map(CareerQuestionOption::getTraitTag)
                    .filter(tag -> tag != null && !tag.isBlank())
                    .forEach(tag -> traitCounts.merge(tag, 1, Integer::sum));
        }

        // Top 3 traits = strength areas
        List<String> strengthAreas = traitCounts.entrySet().stream()
                .sorted(Map.Entry.<String, Integer>comparingByValue().reversed())
                .limit(3)
                .map(Map.Entry::getKey)
                .collect(Collectors.toList());

        // Map traits to interest indicators (deduped)
        Set<String> interestSet = new LinkedHashSet<>();
        for (String trait : strengthAreas) {
            String interest = TRAIT_TO_INTEREST.get(trait);
            if (interest != null) interestSet.add(interest);
        }
        // Fill up to 3 from all answered traits
        for (String trait : traitCounts.keySet()) {
            String interest = TRAIT_TO_INTEREST.get(trait);
            if (interest != null) interestSet.add(interest);
            if (interestSet.size() >= 3) break;
        }
        List<String> interestIndicators = new ArrayList<>(interestSet);

        int totalQuestions = assessment.getQuestions().size();
        int score = totalQuestions > 0
                ? (int) Math.round((answers.size() * 100.0) / totalQuestions)
                : 100;

        return new ComputedResult(strengthAreas, interestIndicators, score);
    }

    private CareerResultResponse toResultResponse(CareerResult r, CareerAssessment a) {
        return CareerResultResponse.builder()
                .resultId(r.getId())
                .assessmentId(a.getId())
                .assessmentTitle(a.getTitle())
                .assessmentType(a.getType().getLabel())
                .completedAt(r.getProgress() != null ? r.getProgress().getCompletedAt() : r.getCreatedAt())
                .strengthAreas(fromJson(r.getStrengthAreasJson()))
                .interestIndicators(fromJson(r.getInterestIndicatorsJson()))
                .score(r.getScore())
                .reportAvailable(r.getReportAvailable())
                .build();
    }


    private String toJson(List<String> list) {
        if (list == null || list.isEmpty()) return "[]";
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < list.size(); i++) {
            sb.append("\"").append(list.get(i).replace("\"", "\\\"")).append("\"");
            if (i < list.size() - 1) sb.append(",");
        }
        sb.append("]");
        return sb.toString();
    }

    private List<String> fromJson(String json) {
        if (json == null || json.isBlank()) return Collections.emptyList();
        try {
            String trimmed = json.trim();
            if (trimmed.equals("[]")) return Collections.emptyList();
            trimmed = trimmed.substring(1, trimmed.length() - 1);
            String[] parts = trimmed.split(",");
            List<String> result = new ArrayList<>();
            for (String part : parts) {
                String clean = part.trim().replaceAll("^\"|\"$", "").replace("\\\"", "\"");
                if (!clean.isEmpty()) result.add(clean);
            }
            return result;
        } catch (Exception e) {
            return Collections.emptyList();
        }
    }
